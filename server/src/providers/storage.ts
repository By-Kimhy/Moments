// Where photos and KHQR images are kept. S3-compatible storage (AWS S3, Cloudflare R2, MinIO)
// when S3_BUCKET is set; otherwise files on disk under UPLOAD_DIR, served by the API.
// Either way the browser loads them from /api/files/<key>, so a key is all the database stores.
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { config } from "../config.js";

export type StoredFile = { body: Buffer; contentType: string };

export interface Storage {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<StoredFile | null>;
  delete(key: string): Promise<void>;
}

const CONTENT_TYPES: Record<string, string> = { ".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg" };

class DiskStorage implements Storage {
  constructor(private dir: string) {}

  private file(key: string) {
    // Keys are generated by the API, but never let one escape the folder.
    if (!/^[\w-]+\.\w+$/.test(key)) throw new Error(`Bad storage key ${key}`);
    return path.join(this.dir, key);
  }

  async put(key: string, body: Buffer) {
    await mkdir(this.dir, { recursive: true });
    await writeFile(this.file(key), body);
  }

  async get(key: string) {
    try {
      const body = await readFile(this.file(key));
      return { body, contentType: CONTENT_TYPES[path.extname(key)] ?? "application/octet-stream" };
    } catch (e) {
      if ((e as NodeJS.ErrnoException).code === "ENOENT") return null;
      throw e;
    }
  }

  async delete(key: string) {
    await rm(this.file(key), { force: true });
  }
}

class S3Storage implements Storage {
  constructor(
    private client: S3Client,
    private bucket: string,
  ) {}

  async put(key: string, body: Buffer, contentType: string) {
    await this.client.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: contentType }));
  }

  async get(key: string) {
    try {
      const res = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
      if (!res.Body) return null;
      return { body: Buffer.from(await res.Body.transformToByteArray()), contentType: res.ContentType ?? "application/octet-stream" };
    } catch (e) {
      if ((e as { name?: string }).name === "NoSuchKey") return null;
      throw e;
    }
  }

  async delete(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

function createStorage(): Storage {
  const s3 = config.s3();
  if (!s3) return new DiskStorage(config.uploadDir());
  const client = new S3Client({
    region: s3.region,
    endpoint: s3.endpoint,
    // MinIO and most self-hosted stores need path-style URLs.
    forcePathStyle: Boolean(s3.endpoint),
    credentials: s3.accessKeyId && s3.secretAccessKey ? { accessKeyId: s3.accessKeyId, secretAccessKey: s3.secretAccessKey } : undefined,
  });
  return new S3Storage(client, s3.bucket);
}

export const storage = createStorage();
